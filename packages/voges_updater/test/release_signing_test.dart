/// [path] as the tool resolves --clone: on Windows it gains a drive letter.
String _absolute(String path) => p.normalize(p.absolute(path));

List<String> _installersOf(SuiteApp app) => [
  app.macos.asset,
  app.windows.asset,
  app.linux.asset,
];

/// The voges_updater entry of a pubspec.lock, as pub writes a git
/// dependency.
String _updaterEntry({
  String source = 'git',
  String url = '"https://github.com/omanoloneto/voges-word.git"',
  String path = '"packages/voges_updater"',
  String resolvedRef = '"$_updaterCommit"',
}) =>
    '''
  voges_updater:
    dependency: "direct main"
    description:
      path: $path
      ref: "$_updaterCommit"
      resolved-ref: $resolvedRef
      url: $url
    source: $source
    version: "1.0.0"
''';

/// A pubspec.lock with [entry] among other packages, one of them another
/// git dependency.
String _lockWith(String entry) =>
    '''
# Generated by pub
# See https://dart.dev/tools/pub/glossary#lockfile
packages:
  async:
    dependency: transitive
    description:
      name: async
      sha256: "758e6d74e971c3e5aceb4110bfd6698efc7f501675bcfe0c775459a8140750eb"
      url: "https://pub.dev"
    source: hosted
    version: "2.13.0"
  other_tool:
    dependency: "direct main"
    description:
      path: "."
      ref: main
      resolved-ref: "$_commit"
      url: "https://github.com/someone/other-tool.git"
    source: git
    version: "0.1.0"
$entry  path:
    dependency: transitive
    description:
      name: path
      sha256: "75cca69d1490965be98c73ceaea117e8a04dd21217b37b292c9ddbec0d955bc5"
      url: "https://pub.dev"
    source: hosted
    version: "1.9.1"
sdks:
  dart: ">=3.11.4 <4.0.0"
  flutter: ">=3.41.0"
''';

Uint8List _sumsOf(Iterable<String> names) => utf8.encode(
  [
    for (final name in names) '${sha256.convert(utf8.encode(name))}  $name\n',
  ].join(),
);

/// The login Keychain as `security` shows it, one release of [app] as `gh`
/// shows it and the clones as `git` shows them. Nothing here touches the
/// real ones.
final class _FakeSystem implements ProcessRunner {
  _FakeSystem([this.app = vogesWord]);

  final SuiteApp app;

  String get repository => app.repository;

  /// The clone with the app's tags: this one for Voges Word.
  String get appClone => app == vogesWord ? _checkout : _pencilClone;

  /// What this clone compares lib/src/release_trust.dart with: the tag for
  /// Voges Word, the voges_updater commit that the app's pubspec.lock pins
  /// for the others.
  String get trustedRevision => app == vogesWord ? _tag : _updaterCommit;

  /// The stored key in base64, or null when there is none.
  String? keychain;
  int searchExitCode = 44;
  int addExitCode = 0;

  bool draft = true;
  late List<String> assets = [..._installersOf(app), checksumsAsset];
  late Uint8List checksums = _sumsOf(_installersOf(app));
  int viewExitCode = 0;

  String author = _bot;
  Map<String, String> uploaders = {};
  Set<String> gitClones = {_checkout, _pencilClone};
  String? localCommit = _commit;
  String remoteCommit = _commit;

  /// The pubspec.lock of the tag in [appClone], or null when it has none.
  String? lock = _lockWith(_updaterEntry());
  bool sameTrustedKeys = true;
  bool trustFileAtRevision = true;
  bool attested = true;

  /// The .sig already on the draft, when [assets] lists it.
  Uint8List? existingSignature;

  final calls = <List<String>>[];
  final interactiveInput = <String>[];
  Uint8List? uploaded;
  bool published = false;
  String? downloadFolder;

  bool get uploadedOrPublished => uploaded != null || published;

  @override
  Future<ProcessResult> run(
    String executable,
    List<String> arguments, {
    String? workingDirectory,
  }) async {
    calls.add([executable, ...arguments]);
    return switch ((executable, arguments)) {
      (_security, ['find-generic-password', '-a', 'voges', '-s', _]) => _result(
        keychain == null ? searchExitCode : 0,
      ),
      (_security, ['find-generic-password', '-a', 'voges', '-s', _, '-w']) =>
        keychain == null ? _result(44) : _result(0, stdout: '$keychain\n'),
      (_git, ['-C', final clone, 'rev-parse', '--git-dir']) =>
        gitClones.contains(clone)
            ? _result(0, stdout: '.git\n')
            : _result(128, stderr: 'fatal: not a git repository'),
      (
        _gh,
        [
          'release',
          'view',
          _tag,
          '--repo',
          final repo,
          '--json',
          'isDraft,assets,databaseId',
        ],
      )
          when repo == repository =>
        _result(
          viewExitCode,
          stdout: jsonEncode({
            'assets': [
              for (final name in assets) {'name': name, 'size': 1},
            ],
            'databaseId': 42,
            'isDraft': draft,
          }),
          stderr: viewExitCode == 0 ? '' : 'release not found',
        ),
      (_gh, ['api', final path]) when path == 'repos/$repository/releases/42' =>
        _result(
          0,
          stdout: jsonEncode({
            'author': {'login': author},
            'assets': [
              for (final name in assets)
                {
                  'name': name,
                  'uploader': {
                    'login':
                        uploaders[name] ??
                        (name == signatureAsset ? 'omanoloneto' : _bot),
                  },
                },
            ],
          }),
        ),
      (_gh, ['api', final path, '--jq', '.sha'])
          when path == 'repos/$repository/commits/$_tag' =>
        _result(0, stdout: '$remoteCommit\n'),
      (_git, ['-C', final clone, 'rev-parse', '--verify', '$_tag^{commit}'])
          when clone == appClone =>
        localCommit == null
            ? _result(128, stderr: 'fatal: Needed a single revision')
            : _result(0, stdout: '$localCommit\n'),
      (_git, ['-C', final clone, 'show', '$_tag:pubspec.lock'])
          when clone == appClone && app != vogesWord =>
        lock == null
            ? _result(128, stderr: 'fatal: path does not exist')
            : _result(0, stdout: lock!),
      (_git, ['-C', _checkout, 'cat-file', '-e', final object])
          when object == '$trustedRevision:./lib/src/release_trust.dart' =>
        _result(trustFileAtRevision ? 0 : 128),
      (
        _git,
        [
          '-C',
          _checkout,
          'diff',
          '--quiet',
          final revision,
          '--',
          'lib/src/release_trust.dart',
        ],
      )
          when revision == trustedRevision && trustFileAtRevision =>
        _result(sameTrustedKeys ? 0 : 1),
      (
        _gh,
        [
          'attestation',
          'verify',
          final file,
          '--repo',
          final repo,
          '--signer-workflow',
          final workflow,
          '--source-ref',
          'refs/tags/$_tag',
          '--source-digest',
          final digest,
          '--deny-self-hosted-runners',
        ],
      )
          when repo == repository &&
              workflow == '$repository/.github/workflows/release.yml' =>
        attested &&
                digest == localCommit &&
                p.basename(file) == checksumsAsset &&
                File(file).existsSync()
            ? _result(0)
            : _result(1, stderr: 'no attestation matches'),
      (
        _gh,
        [
          'release',
          'download',
          _tag,
          '--repo',
          final repo,
          '--pattern',
          checksumsAsset,
          '--dir',
          final folder,
        ],
      )
          when repo == repository =>
        _download(folder),
      (
        _gh,
        [
          'release',
          'download',
          _tag,
          '--repo',
          final repo,
          '--pattern',
          checksumsAsset,
          '--pattern',
          signatureAsset,
          '--dir',
          final folder,
        ],
      )
          when repo == repository =>
        _download(folder, withSignature: true),
      (_gh, ['release', 'upload', _tag, final path, '--repo', final repo])
          when repo == repository =>
        _upload(path),
      (
        _gh,
        [
          'release',
          'edit',
          _tag,
          '--repo',
          final repo,
          '--draft=false',
          '--latest',
        ],
      )
          when repo == repository =>
        _publish(),
      _ => throw StateError('unexpected call: $executable $arguments'),
    };
  }

  @override
  ProcessResult runSync(String executable, List<String> arguments) =>
      throw UnsupportedError('the release tool never runs tools synchronously');

  @override
  Future<Process> start(
    String executable,
    List<String> arguments, {
    String? workingDirectory,
    ProcessStartMode mode = ProcessStartMode.normal,
  }) async {
    calls.add([executable, ...arguments]);
    if (executable != _security || arguments.join(' ') != '-i') {
      throw StateError('unexpected start: $executable $arguments');
    }
    return _InteractiveSecurity((input) {
      interactiveInput.add(input);
      final match = RegExp(
        r'^add-generic-password -a voges -s voges-release-signing -w (\S+)\n$',
      ).firstMatch(input);
      if (match != null && addExitCode == 0) keychain = match[1];
    }, addExitCode);
  }

  ProcessResult _download(String folder, {bool withSignature = false}) {
    downloadFolder = folder;
    File(p.join(folder, checksumsAsset)).writeAsBytesSync(checksums);
    if (withSignature) {
      File(p.join(folder, signatureAsset)).writeAsBytesSync(existingSignature!);
    }
    return _result(0);
  }

  ProcessResult _upload(String path) {
    expect(p.basename(path), signatureAsset);
    expect(draft, isTrue);
    uploaded = File(path).readAsBytesSync();
    return _result(0);
  }

  ProcessResult _publish() {
    expect(uploaded ?? existingSignature, isNotNull);
    published = true;
    draft = false;
    return _result(0);
  }

  static ProcessResult _result(
    int exitCode, {
    String stdout = '',
    String stderr = '',
  }) => ProcessResult(1, exitCode, stdout, stderr);
}

/// `security -i`: reads its commands from stdin.
final class _InteractiveSecurity implements Process {
  _InteractiveSecurity(void Function(String input) onInput, int code) {
    exitCode = utf8.decodeStream(_input.stream).then((input) {
      onInput(input);
      return code;
    });
  }

  final _input = StreamController<List<int>>();

  @override
  late final IOSink stdin = IOSink(_input);

  @override
  late final Future<int> exitCode;

  @override
  Stream<List<int>> get stdout => const Stream.empty();

  @override
  Stream<List<int>> get stderr => const Stream.empty();

  @override
  int get pid => 1;

  @override
  bool kill([ProcessSignal signal = ProcessSignal.sigterm]) => false;
}

void main() {
  late _FakeSystem system;
  late StringBuffer out;
  late StringBuffer err;
  late String publicKey;

  setUpAll(() async => publicKey = await publicKeyOf(_seed));

  setUp(() {
    system = _FakeSystem();
    out = StringBuffer();
    err = StringBuffer();
  });

  Future<int> run(
    List<String> arguments, {
    String? gh = _gh,
    List<String>? trustedKeys,
  }) => ReleaseSigning(
    runner: system,
    gh: gh,
    checkout: _checkout,
    verifier: ReleaseVerifier(trustedKeys: trustedKeys ?? [publicKey]),
    out: out,
    err: err,
  ).run(arguments);

  group('init', () {
    test('stores a new key through stdin and prints its public key', () async {
      expect(await run(['init']), 0, reason: '$err');
      final stored = system.keychain!;
      final seed = base64.decode(stored);
      expect(seed, hasLength(32));
      expect(system.interactiveInput, [
        'add-generic-password -a voges -s voges-release-signing -w $stored\n',
      ]);
      expect(system.calls, contains(equals([_security, '-i'])));
      for (final call in system.calls) {
        expect(call.join(' '), isNot(contains(stored)));
      }
      expect('$out', contains(await publicKeyOf(seed)));
      expect('$out$err', isNot(contains(stored)));
    });

    test('makes a different key each time', () async {
      expect(await run(['init']), 0);
      final first = system.keychain;
      system = _FakeSystem();
      expect(await run(['init']), 0);
      expect(system.keychain, isNot(first));
    });

    test('never replaces a key that exists', () async {
      system.keychain = base64.encode(_seed);
      expect(await run(['init']), 1);
      expect('$err', contains('already'));
      expect(system.keychain, base64.encode(_seed));
      expect(system.interactiveInput, isEmpty);
      expect('$out$err', isNot(contains(base64.encode(_seed))));
    });

    test('stops when security fails', () async {
      system.searchExitCode = 51;
      expect(await run(['init']), 1);
      expect(system.interactiveInput, isEmpty);

      system
        ..searchExitCode = 44
        ..addExitCode = 45;
      expect(await run(['init']), 1);
      expect(system.keychain, isNull);
      expect('$out', isEmpty);
    });
  });

  group('public-key', () {
    test('prints the public key of the stored key, never the key', () async {
      system.keychain = base64.encode(_seed);

      expect(await run(['public-key']), 0);
      expect('$out'.trim(), publicKey);
      expect('$out$err', isNot(contains(system.keychain!)));
    });

    test('needs the key', () async {
      expect(await run(['public-key']), 1);
      expect('$err', contains('Run init first'));
    });
  });

  group('publish', () {
    setUp(() => system.keychain = base64.encode(_seed));

    test('signs the draft, uploads the signature and publishes', () async {
      expect(await run(['publish', _repository, _tag]), 0, reason: '$err');
      expect(system.published, isTrue);
      expect(
        await ReleaseVerifier(trustedKeys: [publicKey]).verify(
          repository: _repository,
          version: _version,
          checksums: system.checksums,
          signature: system.uploaded!,
        ),
        hasLength(3),
      );
      expect(system.calls.map((call) => call.take(3).join(' ')), [
        '$_gh release view',
        '$_gh api repos/omanoloneto/voges-word/releases/42',
        '$_git -C $_checkout',
        '$_gh api repos/omanoloneto/voges-word/commits/$_tag',
        '$_git -C $_checkout',
        '$_git -C $_checkout',
        '$_gh release download',
        '$_gh attestation verify',
        '$_security find-generic-password -a',
        '$_gh release upload',
        '$_gh release edit',
      ]);
      expect(Directory(system.downloadFolder!).existsSync(), isFalse);
      expect('$out$err', isNot(contains(system.keychain!)));
    });

    test('finishes a publish that stopped after the upload', () async {
      system
        ..assets = [...system.assets, signatureAsset]
        ..existingSignature = await signChecksums(
          seed: _seed,
          repository: _repository,
          version: _version,
          checksums: system.checksums,
        );

      expect(await run(['publish', _repository, _tag]), 0, reason: '$err');
      expect(system.uploaded, isNull);
      expect(system.published, isTrue);
    });

    test('a dry run signs and checks but changes nothing', () async {
      expect(await run(['publish', _repository, _tag, '--dry-run']), 0);
      expect(system.uploadedOrPublished, isFalse);
      expect('$out', contains('Dry run'));
    });

    test('refuses a key the apps do not trust', () async {
      final other = await publicKeyOf(List.filled(32, 1));
      expect(
        await run(['publish', _repository, _tag], trustedKeys: [other]),
        1,
      );
      expect('$err', contains('releaseSigningKeys'));
      expect(system.uploadedOrPublished, isFalse);
    });

    final refusals = <String, (void Function(_FakeSystem system), String)>{
      'a published release': (
        (system) => system.draft = false,
        'already published',
      ),
      'a signature this key did not make': (
        (system) => system
          ..assets = [...system.assets, signatureAsset]
          ..existingSignature = utf8.encode(
            '${base64.encode(List.filled(64, 7))}\n',
          ),
        'did not make',
      ),
      'a draft another account created': (
        (system) => system.author = 'someone',
        'created by someone',
      ),
      'an installer another account uploaded': (
        (system) => system.uploaders = {_installers.first: 'someone'},
        'uploaded by someone',
      ),
      'a tag that moved on GitHub': (
        (system) => system.remoteCommit = 'f' * 40,
        'on GitHub',
      ),
      'a tag missing from this clone': (
        (system) => system.localCommit = null,
        'not in this clone',
      ),
      'a tag without the trusted keys file': (
        (system) => system.trustFileAtRevision = false,
        'has no lib/src/release_trust.dart',
      ),
      'a tag that trusts other keys': (
        (system) => system.sameTrustedKeys = false,
        'release_trust.dart',
      ),
      'checksums the workflow did not attest': (
        (system) => system.attested = false,
        'attestation verify',
      ),
      'a release without an installer': (
        (system) => system.assets = [_installers.first, checksumsAsset],
        'should have exactly',
      ),
      'a release with an extra file': (
        (system) => system.assets = [...system.assets, 'notes.txt'],
        'should have exactly',
      ),
      'checksums of other files': (
        (system) =>
            system.checksums = _sumsOf([..._installers.skip(1), 'other.dmg']),
        'should list exactly',
      ),
      'checksums missing an installer': (
        (system) => system.checksums = _sumsOf(_installers.skip(1)),
        'should list exactly',
      ),
      'malformed checksums': (
        (system) => system.checksums = utf8.encode('not checksums\n'),
        'is malformed',
      ),
      'a Keychain without the key': (
        (system) => system.keychain = null,
        'Run init first',
      ),
      'a Keychain item that is not a key': (
        (system) => system.keychain = base64.encode([1, 2, 3]),
        'not a 32-byte key',
      ),
      'a release gh cannot find': (
        (system) => system.viewExitCode = 1,
        'release not found',
      ),
    };
    for (final MapEntry(key: name, value: (arrange, reason))
        in refusals.entries) {
      test('refuses $name', () async {
        arrange(system);
        expect(await run(['publish', _repository, _tag]), 1);
        expect('$err', contains(reason));
        expect(system.uploadedOrPublished, isFalse);
      });
    }

    test('refuses repositories and tags outside the suite', () async {
      expect(await run(['publish', 'someone/else', _tag]), 1);
      for (final tag in ['1.2.0', 'v1.2', 'v1.2.0-rc1']) {
        expect(await run(['publish', _repository, tag]), 1, reason: tag);
      }
      expect(system.calls, isEmpty);
    });

    test('needs gh', () async {
      expect(await run(['publish', _repository, _tag], gh: null), 1);
      expect('$err', contains('gh'));
      expect(system.calls, isEmpty);
    });

    test('refuses --clone: the tags are in this clone', () async {
      expect(
        await run(['publish', _repository, _tag, '--clone', _pencilClone]),
        1,
      );
      expect('$err', contains('without --clone'));
      expect(system.calls, isEmpty);
    });
  });

  group('publish an app of another repository', () {
    final pencil = vogesPencil.repository;

    setUp(
      () => system = _FakeSystem(vogesPencil)..keychain = base64.encode(_seed),
    );

    Future<int> publish({List<String> flags = const []}) =>
        run(['publish', pencil, _tag, '--clone', _pencilClone, ...flags]);

    test('checks the tag in its clone and the voges_updater it pins', () async {
      expect(await publish(), 0, reason: '$err');
      expect(system.published, isTrue);
      expect(
        await ReleaseVerifier(trustedKeys: [publicKey]).verify(
          repository: pencil,
          version: _version,
          checksums: system.checksums,
          signature: system.uploaded!,
        ),
        hasLength(3),
      );
      expect(system.calls.map((call) => call.take(3).join(' ')), [
        '$_git -C $_pencilClone',
        '$_gh release view',
        '$_gh api repos/omanoloneto/voges-pencil/releases/42',
        '$_git -C $_pencilClone',
        '$_gh api repos/omanoloneto/voges-pencil/commits/$_tag',
        '$_git -C $_pencilClone',
        '$_git -C $_checkout',
        '$_git -C $_checkout',
        '$_gh release download',
        '$_gh attestation verify',
        '$_security find-generic-password -a',
        '$_gh release upload',
        '$_gh release edit',
      ]);
      expect(system.calls.where((call) => call.first == _git), [
        [_git, '-C', _pencilClone, 'rev-parse', '--git-dir'],
        [_git, '-C', _pencilClone, 'rev-parse', '--verify', '$_tag^{commit}'],
        [_git, '-C', _pencilClone, 'show', '$_tag:pubspec.lock'],
        [
          _git,
          '-C',
          _checkout,
          'cat-file',
          '-e',
          '$_updaterCommit:./lib/src/release_trust.dart',
        ],
        [
          _git,
          '-C',
          _checkout,
          'diff',
          '--quiet',
          _updaterCommit,
          '--',
          'lib/src/release_trust.dart',
        ],
      ]);
      expect(Directory(system.downloadFolder!).existsSync(), isFalse);
    });

    test('a dry run signs and checks but changes nothing', () async {
      expect(
        await run([
          'publish',
          pencil,
          _tag,
          '--dry-run',
          '--clone',
          _pencilClone,
        ]),
        0,
        reason: '$err',
      );
      expect(system.uploadedOrPublished, isFalse);
      expect('$out', contains('Dry run: $pencil $_tag'));
    });

    test('accepts the voges-word URL without .git', () async {
      system.lock = _lockWith(
        _updaterEntry(url: '"https://github.com/omanoloneto/voges-word"'),
      );

      expect(await publish(), 0, reason: '$err');
      expect(system.published, isTrue);
    });

    test('needs --clone', () async {
      expect(await run(['publish', pencil, _tag]), 1);
      expect('$err', contains('--clone'));
      expect(system.calls, isEmpty);
    });

    test('refuses a folder that is not a git clone', () async {
      final nothing = _absolute('/clones/nothing');
      expect(await run(['publish', pencil, _tag, '--clone', nothing]), 1);
      expect('$err', contains('$nothing is not a git clone'));
      expect(system.calls, [
        [_git, '-C', nothing, 'rev-parse', '--git-dir'],
      ]);
    });

    final refusals = <String, (void Function(_FakeSystem system), String)>{
      'a tag missing from its clone': (
        (system) => system.localCommit = null,
        '$_tag is not in $_pencilClone',
      ),
      'a tag that moved on GitHub': (
        (system) => system.remoteCommit = 'f' * 40,
        'on GitHub',
      ),
      'a tag without pubspec.lock': (
        (system) => system.lock = null,
        'has no pubspec.lock',
      ),
      'a pubspec.lock without voges_updater': (
        (system) => system.lock = _lockWith(''),
        'does not list voges_updater',
      ),
      'a pubspec.lock that pub did not write': (
